// humis-g1: see the rear_clip_* globals. Removes points that lie in the rear
// base_link sector AND beyond rear_clip_max_range. base_link<-cloud is built from
// the same URDF TF the compose uses (mid360_link->base_link) plus cloud_to_lidar_R;
// on a transient TF dropout it reuses the cache, and before the first good TF it
// keeps all points (cannot define "rear" yet). Compacts the cloud in place.
void rear_clip_filter(PointCloudXYZI::Ptr &cloud)
{
    if (!rear_clip_enable || !cloud || cloud->empty()) return;

    Eigen::Isometry3d T_LB = Eigen::Isometry3d::Identity();
    bool have_tf = false;
    try {
        const geometry_msgs::TransformStamped tfm =
            g_tf_buffer->lookupTransform(lidar_frame_id, base_frame_id, ros::Time(0));
        const Eigen::Quaterniond q_LB(tfm.transform.rotation.w, tfm.transform.rotation.x,
                                      tfm.transform.rotation.y, tfm.transform.rotation.z);
        T_LB.linear() = q_LB.toRotationMatrix();
        T_LB.translation() = V3D(tfm.transform.translation.x, tfm.transform.translation.y,
                                 tfm.transform.translation.z);
        g_T_LB_cache = T_LB;
        g_T_LB_valid = true;
        have_tf = true;
    } catch (const tf2::TransformException &ex) {
        if (g_T_LB_valid) { T_LB = g_T_LB_cache; have_tf = true; }
    }
    if (!have_tf) {
        ROS_WARN_THROTTLE(5.0,
            "g1_slam_frontend: rear_clip skipped, no %s->%s TF yet (bring up start_state)",
            lidar_frame_id.c_str(), base_frame_id.c_str());
        return;
    }

    const Eigen::Isometry3d T_BM = T_LB.inverse();      // base_link <- mid360_link
    // base_link <- real cloud frame. cloud_to_lidar_R is R(cloud<-mid360) (the
    // convention publish_odometry's T_FM uses), so mid360<-cloud is its transpose.
    // Using .transpose() (not the bare matrix) keeps this correct even if
    // cloud_to_lidar_R is ever set to a non-involutory rotation; for the default
    // 180-about-X it equals itself, so today's output is unchanged.
    const M3D R_BC = T_BM.linear() * cloud_to_lidar_R.transpose();
    const V3D t_BC = T_BM.translation();

    size_t kept = 0;
    for (size_t i = 0; i < cloud->points.size(); ++i) {
        const auto &p = cloud->points[i];
        const V3D pb = R_BC * V3D(p.x, p.y, p.z) + t_BC;
        const double hr = std::sqrt(pb.x() * pb.x() + pb.y() * pb.y());
        // In the rear sector iff the horizontal bearing is within sector/2 of -X:
        // -x_b / hr >= cos(sector/2)  <=>  x_b <= -cos_half * hr (no trig per point).
        if (pb.x() <= -rear_clip_cos_half * hr && hr > rear_clip_max_range) continue;
        cloud->points[kept++] = cloud->points[i];
    }
    cloud->points.resize(kept);
    cloud->width = static_cast<uint32_t>(kept);
    cloud->height = 1;
}

void publish_odometry(const ros::Publisher & pubOdomAftMapped)
{
    // humis-g1 port: publish odom->base_link, not the upstream
    // odom->sensor. T(odom->mid360_link) comes from the estimated state plus the
    // lidar-IMU extrinsic; T(mid360_link->base_link) is read live from TF
    // (robot_state_publisher, so waist_yaw is accounted for). The upstream
    // odom->body TF broadcast is replaced (it would give mid360_link two parents
    // and break the TF tree).
    const M3D R_OL = state_point.rot.toRotationMatrix() *
                     state_point.offset_R_L_I.toRotationMatrix();
    const V3D t_OL = state_point.pos + state_point.rot * state_point.offset_T_L_I;

    Eigen::Isometry3d T_LB = Eigen::Isometry3d::Identity();
    try {
        const geometry_msgs::TransformStamped tfm =
            g_tf_buffer->lookupTransform(lidar_frame_id, base_frame_id, ros::Time(0));
        const Eigen::Quaterniond q_LB(tfm.transform.rotation.w, tfm.transform.rotation.x,
                                      tfm.transform.rotation.y, tfm.transform.rotation.z);
        T_LB.linear() = q_LB.toRotationMatrix();
        T_LB.translation() = V3D(tfm.transform.translation.x, tfm.transform.translation.y,
                                 tfm.transform.translation.z);
        g_T_LB_cache = T_LB;     // remember the last good URDF transform
        g_T_LB_valid = true;
    } catch (const tf2::TransformException &ex) {
        if (g_T_LB_valid) {
            // Transient dropout: reuse the last good mid360_link->base_link. The value
            // is still the URDF one (via robot_state_publisher), just slightly stale.
            T_LB = g_T_LB_cache;
            ROS_WARN_THROTTLE(5.0,
                "g1_slam_frontend: TF %s->%s unavailable (%s); reusing last-known transform",
                lidar_frame_id.c_str(), base_frame_id.c_str(), ex.what());
        } else {
            // No good transform yet (startup, or no URDF TF tree is running). Fall back
            // to identity so base_link coincides with the sensor until TF appears. Bring
            // up g1_description's robot_state_publisher fed by /joint_states to fix this.
            ROS_WARN_THROTTLE(5.0,
                "g1_slam_frontend: TF %s->%s unavailable (%s) and no cached transform; "
                "odom->base_link uses identity (base_link == sensor)",
                lidar_frame_id.c_str(), base_frame_id.c_str(), ex.what());
        }
    }

    Eigen::Isometry3d T_OL = Eigen::Isometry3d::Identity();
    T_OL.linear() = R_OL;
    T_OL.translation() = t_OL;
    // Reconcile the real (inverted) cloud frame to the URDF mid360_link frame
    // before applying the URDF TF mid360_link->base_link.
    Eigen::Isometry3d T_FM = Eigen::Isometry3d::Identity();
    T_FM.linear() = cloud_to_lidar_R;
    const Eigen::Isometry3d T_OB = T_OL * T_FM * T_LB;   // odom -> base_link
    const Eigen::Quaterniond q_OB(T_OB.linear());
    const V3D t_OB = T_OB.translation();

    odomAftMapped.header.frame_id = odom_frame_id;
    odomAftMapped.child_frame_id = base_frame_id;
    odomAftMapped.header.stamp = ros::Time().fromSec(lidar_end_time);
    odomAftMapped.pose.pose.position.x = t_OB.x();
    odomAftMapped.pose.pose.position.y = t_OB.y();
    odomAftMapped.pose.pose.position.z = t_OB.z();
    odomAftMapped.pose.pose.orientation.x = q_OB.x();
    odomAftMapped.pose.pose.orientation.y = q_OB.y();
    odomAftMapped.pose.pose.orientation.z = q_OB.z();
    odomAftMapped.pose.pose.orientation.w = q_OB.w();
    pubOdomAftMapped.publish(odomAftMapped);
    auto P = kf.get_P();
    for (int i = 0; i < 6; i ++)
    {
        int k = i < 3 ? i + 3 : i - 3;
        odomAftMapped.pose.covariance[i*6 + 0] = P(k, 3);
        odomAftMapped.pose.covariance[i*6 + 1] = P(k, 4);
        odomAftMapped.pose.covariance[i*6 + 2] = P(k, 5);
        odomAftMapped.pose.covariance[i*6 + 3] = P(k, 0);
        odomAftMapped.pose.covariance[i*6 + 4] = P(k, 1);
        odomAftMapped.pose.covariance[i*6 + 5] = P(k, 2);
    }

    static tf::TransformBroadcaster br;
    tf::Transform                   transform;
    tf::Quaternion                  q;
    transform.setOrigin(tf::Vector3(t_OB.x(), t_OB.y(), t_OB.z()));
    q.setW(q_OB.w());
    q.setX(q_OB.x());
    q.setY(q_OB.y());
    q.setZ(q_OB.z());
    transform.setRotation( q );
    br.sendTransform( tf::StampedTransform( transform, odomAftMapped.header.stamp, odom_frame_id, base_frame_id ) );
}

